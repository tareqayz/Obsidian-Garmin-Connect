/** The index as the walk leaves it: 435 rows, oldest first. */
export function historyRows(): TrainingStatusRow[] {
	const changes = new Map(
		PHRASES.trim()
			.split(/\s+/)
			.map((pair) => pair.split("=") as [string, string])
			.map(([day, phrase]) => [`20${day}`, phrase]),
	);
	const full = new Map(
		FULL.trim()
			.split("\n")
			.map((line) => {
				const [date, code, phrase, acute, chronic, ratio, acwr, pct, feedback, trend, sport] = line.trim().split(/\s+/).map((v) => (v === "-" ? undefined : v));
				const n = (v: string | undefined) => (v === undefined ? undefined : Number(v));
				return [date!, { date, code: n(code), phrase, acute: n(acute), chronic: n(chronic), ratio: n(ratio), acwr, acwrPct: n(pct), acwrFeedback: feedback, trend: n(trend), trendSport: sport }];
			}),
	);
	const rows: TrainingStatusRow[] = [];
	let phrase: string | undefined;
	for (const line of CODES.trim().split("\n")) {
		const [start, codes] = line.trim().split(" ") as [string, string];
		[...codes].forEach((c, i) => {
			const date = shiftDate(start, i);
			phrase = changes.get(date) ?? phrase;
			if (c === ".") return;
			rows.push(TRAINING_STATUS_INDEX.normalize(full.get(date) ?? { date, code: Number(c), phrase, trendSport: "RUNNING" })!);
		});
	}
	return rows;
}

