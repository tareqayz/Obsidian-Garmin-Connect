function poolLength([n, start, duration, hr, maxHr, swum]: Length) {
	const length = { lengthIndex: n, startTimeGMT: gmt(POOL_START, start), duration, averageHR: hr, maxHR: maxHr };
	if (!swum) return length;
	const [distance, speed, strokes, swolf] = swum;
	return { ...length, distance, averageSpeed: speed, maxSpeed: speed, totalNumberOfStrokes: strokes, averageSWOLF: swolf, swimStroke: "FREESTYLE" };
}

