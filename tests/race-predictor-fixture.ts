export function rowsOf(...blocks: string[]): RacePredictionRow[] {
	const byDate = new Map<string, RacePredictionRow>();
	for (const line of blocks.join("\n").split("\n")) {
		const [date, ...times] = line.trim().split(/\s+/);
		if (!date || times[0] === "-" || !times.length) continue;
		const [time5k, time10k, half, marathon] = times.map(Number);
		byDate.set(date, { date, time5k: time5k!, time10k: time10k!, half: half!, marathon: marathon! });
	}
	return [...byDate.values()].sort((a, b) => (a.date < b.date ? -1 : 1));
}

