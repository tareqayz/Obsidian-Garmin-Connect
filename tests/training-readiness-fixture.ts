/** The readings of a block of lines, in its order, field for field as Garmin sends them. */
export function readingsOf(text: string): TrainingReadinessReading[] {
	const n = (v: string | undefined) => (v === undefined || v === "-" ? null : Number(v));
	return text
		.trim()
		.split("\n")
		.map((line) => {
			const [date, gmt, local, ctx, score, level, short, long, sleep, recovery, acwr, hrv, sleepHistory, stressHistory, phrase] = line.trim().split(/\s+/) as string[];
			const [sleepScore, sleepPct, sleepFb] = sleep!.split("/");
			const [minutes, recoveryPct, recoveryFb] = recovery!.split("/");
			const [acute, acwrPct, acwrFb] = acwr!.split("/");
			const [weekly, hrvPct, hrvFb] = hrv!.split("/");
			const [sleepHistoryPct, sleepHistoryFb] = sleepHistory!.split("/");
			const [stressHistoryPct, stressHistoryFb] = stressHistory!.split("/");
			return {
				userProfilePK: 136055941,
				calendarDate: date!,
				timestamp: `${gmt}.0`,
				timestampLocal: `${date}T${local}.0`,
				deviceId: 3611994638,
				level: level!,
				feedbackLong: long!,
				feedbackShort: short!,
				score: n(score),
				sleepScore: n(sleepScore),
				sleepScoreFactorPercent: n(sleepPct),
				sleepScoreFactorFeedback: sleepFb!,
				recoveryTime: n(minutes),
				recoveryTimeFactorPercent: n(recoveryPct),
				recoveryTimeFactorFeedback: recoveryFb!,
				acwrFactorPercent: n(acwrPct),
				acwrFactorFeedback: acwrFb!,
				acuteLoad: n(acute),
				stressHistoryFactorPercent: n(stressHistoryPct),
				stressHistoryFactorFeedback: stressHistoryFb!,
				hrvFactorPercent: n(hrvPct),
				hrvFactorFeedback: hrvFb!,
				hrvWeeklyAverage: n(weekly),
				sleepHistoryFactorPercent: n(sleepHistoryPct),
				sleepHistoryFactorFeedback: sleepHistoryFb!,
				validSleep: sleepScore !== "-",
				inputContext: CONTEXTS[ctx!]!,
				primaryActivityTracker: true,
				recoveryTimeChangePhrase: phrase === "-" ? null : phrase!,
			};
		});
}

/** Every reading above, newest first. */
export const ALL = readingsOf(READINGS);

/** A day's readings as `trainingreadiness/{date}` sends them: newest first, [] for a day without one. */
export function dayReadingsOf(date: string): TrainingReadinessReading[] {
	return ALL.filter((r) => r.calendarDate === date);
}

/** The readings of a span as `trainingreadiness/{start}/{end}` sends them: newest first. */
export function rangeOf(start: string, end: string): TrainingReadinessReading[] {
	return ALL.filter((r) => r.calendarDate! >= start && r.calendarDate! <= end);
}

