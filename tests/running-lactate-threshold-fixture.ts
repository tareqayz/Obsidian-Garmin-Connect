const change = (day: string, value: number): BiometricChange => ({ from: day, until: day, series: "running", value, updatedDate: day });

/** `lactateThresholdHeartRate/range/{start}/{end}`: the window's rows, oldest first, `[]` for none. */
export function hrPayload(start: string, end: string): BiometricChange[] {
	return CHANGES.filter(([day]) => day >= start && day <= end).map(([day, hr]) => change(day, hr));
}

/** `lactateThresholdSpeed/range/{start}/{end}`. */
export function speedPayload(start: string, end: string): BiometricChange[] {
	return CHANGES.filter(([day]) => day >= start && day <= end).map(([day, , speed]) => change(day, speed));
}

